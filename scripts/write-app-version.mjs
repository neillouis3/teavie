import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "src/lib/appVersion.ts");

function commitCount() {
  try {
    const raw = execSync("git rev-list --count HEAD", {
      cwd: root,
      encoding: "utf8",
    }).trim();
    const n = Number.parseInt(raw, 10);
    return Number.isFinite(n) && n >= 0 ? n : 0;
  } catch {
    return 0;
  }
}

/** 2.{major}.{minor} — major = commits / 100, minor = commits % 100 */
function formatAppVersion(count) {
  const major = Math.floor(count / 100);
  const minor = count % 100;
  return `2.${major}.${minor}`;
}

const commits = commitCount();
const version = formatAppVersion(commits);

writeFileSync(
  outPath,
  `/** Generated by scripts/write-app-version.mjs — do not edit by hand. */\nexport const APP_COMMIT_COUNT = ${commits};\nexport const APP_VERSION = "${version}";\n`
);

console.log(`App version: ${version} (${commits} commits)`);
